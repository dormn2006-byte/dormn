export const INDIAN_COLLEGES = RAW_COLLEGES.map(([name, city, state, type]) => ({
  name,
  city,
  state,
  type,
  searchIndex: `${name} ${city} ${state} ${type}`.toLowerCase()
}));

export const filterColleges = (query, limit = 35) => {
  if (!query || typeof query !== "string" || !query.trim()) {
    return INDIAN_COLLEGES.slice(0, limit);
  }
  const q = query.trim().toLowerCase();
  const tokens = q.split(/\s+/).filter(Boolean);

  const direct = [];
  const matched = [];

  for (let i = 0; i < INDIAN_COLLEGES.length; i++) {
    const item = INDIAN_COLLEGES[i];
    if (item.name.toLowerCase().startsWith(q) || item.city.toLowerCase().startsWith(q)) {
      direct.push(item);
    } else if (tokens.every(tok => item.searchIndex.includes(tok))) {
      matched.push(item);
    }
    if (direct.length + matched.length >= limit * 1.5) break;
  }

  return [...direct, ...matched].slice(0, limit);
};
